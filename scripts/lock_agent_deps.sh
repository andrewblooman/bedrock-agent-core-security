#!/usr/bin/env bash
# Resolve agent dependencies for the AgentCore runtime (Linux arm64, CPython 3.14)
# and write agent/requirements.lock with pinned versions and sha256 hashes.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
wheels="$(mktemp -d)"
trap 'rm -rf "$wheels"' EXIT

python3.14 -m pip download -q -r "$root/agent/requirements.in" -d "$wheels" \
  --platform manylinux2014_aarch64 --platform manylinux_2_28_aarch64 --platform manylinux_2_34_aarch64 \
  --python-version 3.14 --implementation cp --only-binary=:all:

python3.14 - "$wheels" "$root/agent/requirements.lock" <<'PY'
import hashlib, pathlib, re, sys
wheels, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
lines = ["# Generated by scripts/lock_agent_deps.sh - linux/arm64 cp314. Do not edit.\n"]
for whl in sorted(wheels.glob("*.whl"), key=lambda p: p.name.lower()):
    name, version = whl.name.split("-")[:2]
    digest = hashlib.sha256(whl.read_bytes()).hexdigest()
    lines.append(f"{re.sub(r'[-_.]+', '-', name).lower()}=={version} \\\n    --hash=sha256:{digest}\n")
out.write_text("".join(lines))
print(f"locked {len(lines) - 1} packages -> {out}")
PY
